#!/usr/bin/env bash

set -euo pipefail

# Run as on CI: without the user's global or system Git configuration, so a
# test cannot depend on a local Git identity or setting.
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1

source_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
tmp="$(mktemp -d "${TMPDIR:-/tmp}/attribution-test.XXXXXX")"

cleanup() {
  rm -rf "$tmp"
}
trap cleanup EXIT

fail() {
  echo "attribution test failed: $*" >&2
  exit 1
}

source "$source_root/tests/lib-fakes.sh"
source "$source_root/scripts/lib/attribution.sh"

# The preference: absent, allowed, disabled; anything else is refused instead
# of guessed.
mkdir -p "$tmp/project/.agents"
[[ "$(attribution_preference "$tmp/project")" == "unconfigured" ]] || fail "a project without the file is not unconfigured"
printf '# comment only\n\n' >"$tmp/project/.agents/attribution.conf"
[[ "$(attribution_preference "$tmp/project")" == "unconfigured" ]] || fail "a file without the setting is not unconfigured"
printf '# agents\nagent-attribution: allowed\n' >"$tmp/project/.agents/attribution.conf"
[[ "$(attribution_preference "$tmp/project")" == "allowed" ]] || fail "allowed was not read"
printf 'agent-attribution:   disabled  \n' >"$tmp/project/.agents/attribution.conf"
[[ "$(attribution_preference "$tmp/project")" == "disabled" ]] || fail "disabled was not read"

expect_invalid() {
  local description="$1"
  local output

  printf '%s\n' "$2" >"$tmp/project/.agents/attribution.conf"
  if output="$(attribution_preference "$tmp/project" 2>&1)"; then
    fail "accepted: $description (got '$output')"
  fi
  grep -Fq "Error:" <<<"$output" || fail "no reason was given for: $description"
}
expect_invalid "an unknown value" "agent-attribution: sometimes"
expect_invalid "an unknown setting" "attribution: allowed"
expect_invalid "a malformed line" "agent-attribution allowed"
expect_invalid "a duplicate setting" $'agent-attribution: allowed\nagent-attribution: disabled'

# ATTRIBUTION_CONFIG_FILE selects another file.
printf 'agent-attribution: disabled\n' >"$tmp/other.conf"
printf 'agent-attribution: allowed\n' >"$tmp/project/.agents/attribution.conf"
[[ "$(ATTRIBUTION_CONFIG_FILE="$tmp/other.conf" attribution_preference "$tmp/project")" == "disabled" ]] ||
  fail "ATTRIBUTION_CONFIG_FILE was not used"

# Trailers of agents are found by their address or their '[bot]' name, in any
# case of the key; a person is never taken for an agent, also with a first
# name that is a product's.
message='Add the marker

Some body text that mentions Claude and noreply@anthropic.com in prose.

Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>
Co-authored-by: Claude Dupont <claude.dupont@example.com>
co-authored-by: Cursor <cursoragent@cursor.com>
Co-authored-by: Codex <noreply@openai.com>
Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>
Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>
Co-authored-by: Jane Doe <jane@example.com>
Co-authored-by: Copilot Fan <fan@example.com>
Signed-off-by: Claude Dupont <claude.dupont@example.com>'
found="$(attribution_agent_trailers <<<"$message")"
for agent in "noreply@anthropic.com" "cursoragent@cursor.com" "noreply@openai.com" "175728472+Copilot@users.noreply.github.com" "devin-ai-integration[bot]"; do
  grep -Fq "$agent" <<<"$found" || fail "the agent trailer was not found: $agent"
done
[[ "$(grep -c . <<<"$found")" -eq 5 ]] || fail "expected 5 agent trailers, got: $found"
for person in "claude.dupont@example.com" "jane@example.com" "fan@example.com"; do
  if grep -Fq "$person" <<<"$found"; then fail "a person was taken for an agent: $person"; fi
done
[[ -z "$(attribution_agent_trailers <<<"Co-authored-by: Jane Doe <jane@example.com>")" ]] || fail "a lone human co-author was flagged"

# Generated attribution text: the clients' lines, not ordinary prose.
text='## What changed
The marker, as the Issue asks.
Generated with the help of the team.
🤖 Generated with [Claude Code](https://claude.com/claude-code)
Made with Cursor
generated by Codex CLI
Claude-Session: https://claude.ai/code/session_abc
Agent-Logs-Url: https://github.com/example/project/sessions/1'
found="$(attribution_generated_lines <<<"$text")"
[[ "$(grep -c . <<<"$found")" -eq 5 ]] || fail "expected 5 generated lines, got: $found"
if grep -Fq "help of the team" <<<"$found"; then fail "ordinary prose was taken for attribution"; fi
if grep -Fq "The marker" <<<"$found"; then fail "ordinary prose was taken for attribution"; fi

# Commits: only those the range selects are checked, each agent trailer with
# its commit; a human co-author gives nothing.
repo="$tmp/repo"
git init -q -b main "$repo"
git -C "$repo" config user.name "Attribution Test"
git -C "$repo" config user.email "attribution-test@example.com"
printf 'seed\n' >"$repo/seed.txt"
git -C "$repo" add seed.txt
git -C "$repo" commit -qm "Seed" -m "Co-authored-by: Claude <noreply@anthropic.com>"
git -C "$repo" switch -q -c feature/12-marker
printf 'one\n' >"$repo/one.txt"
git -C "$repo" add one.txt
git -C "$repo" commit -qm "First" -m "Co-authored-by: Jane Doe <jane@example.com>"
printf 'two\n' >"$repo/two.txt"
git -C "$repo" add two.txt
git -C "$repo" commit -qm "Second" -m "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" -m "Co-authored-by: Cursor <cursoragent@cursor.com>"
found="$(attribution_commit_trailers "$repo" main..HEAD)"
[[ "$(grep -c . <<<"$found")" -eq 2 ]] || fail "expected the 2 agent trailers of the branch, got: $found"
grep -q "^$(git -C "$repo" rev-parse --short HEAD)	Second	Co-authored-by: Claude Opus 5.5 <noreply@anthropic.com>$" <<<"$found" ||
  fail "the trailer is not reported with its commit: $found"
if grep -Fq "Seed" <<<"$found"; then fail "a commit of the base was checked"; fi
if grep -Fq "First" <<<"$found"; then fail "a human co-author was reported"; fi
[[ -z "$(attribution_commit_trailers "$repo" main..HEAD~1)" ]] || fail "a range without agent trailers reported some"
[[ "$(printf '%s\n' "$found" | attribution_format_commits | grep -c .)" -eq 4 ]] || fail "the report does not show each trailer under its commit"

echo "attribution tests passed"
